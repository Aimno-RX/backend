def filter_empty_chunks(chunk_documents):
    """
    过滤空的或完全无医学内容的chunk（宽松策略，避免误杀场景性医学文本）
    """
    import re

    invalid_patterns = [
        r'^\s*$',
        r'^\d+\s*$',
        r'^ISBN[：:]\s*',
        r'^版权所有',
    ]

    filtered_chunks = []

    for chunk_doc in chunk_documents:
        content = chunk_doc.page_content.strip()

        if not content or len(content) < 10:
            continue

        is_invalid = False
        for pattern in invalid_patterns:
            if re.match(pattern, content):
                is_invalid = True
                break

        if is_invalid:
            continue

        medical_chars = [
            '病', '症', '治', '疗', '药', '痛', '伤', '损', '炎',
            '椎', '肌', '神经', '血管', '骨', '关节', '脊',
            '颈', '肩', '腰', '背', '头', '臂', '手',
            '姿势', '坐姿', '座椅', '枕', '驾',
            '按摩', '按揉', '推', '拿', '摩', '擦', '耸', '屈', '伸', '旋',
            '穴', '保健', '锻炼', '活动', '运动', '预防', '防止',
            '患者', '临床', '诊断', '检查',
            # 新增：疼痛机制/神经科学相关
            '感受器', '纤维', '通路', '突触', '受体', '递质',
            '敏化', '阈值', '兴奋', '抑制', '皮质', '丘脑',
            '应激', '焦虑', '抑郁', '心理', '遗传', '基因',
            '炎症', '细胞因子', '白细胞', '免疫', '蛋白',
        ]

        has_medical_content = any(char in content for char in medical_chars)

        if not has_medical_content:
            continue

        filtered_chunks.append(chunk_doc)

    return filtered_chunks

def has_valid_entities(graph_document):
    """
    检查图文档是否包含有效的实体
    """
    if not graph_document.nodes:
        return False
    valid_nodes = [node for node in graph_document.nodes if node.id and len(str(node.id).strip()) > 0]
    return len(valid_nodes) > 0

